const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const nodes={},commands=[];
const node=id=>nodes[id]??={value:'',checked:false,style:{},addEventListener(){}};
const axes=Object.fromEntries(['X','Y'].map(axis=>[axis,{port:{},seen:Date.now(),last:{position_full_steps:0,motor_enabled:false,capabilities:{soft_limits_supported:true}},async send(cmd,fields){commands.push(JSON.parse(JSON.stringify({axis,cmd,fields})));if(cmd==='set_soft_limits'){this.last.soft_limits_enabled=fields.enabled;this.last.soft_limit_min_full_steps=fields.min_full_steps;this.last.soft_limit_max_full_steps=fields.max_full_steps;}}}]));
let message='';
const jog={ready:()=>true,stop:async()=>{},analog:{}};
const sandbox={document:{getElementById:node},navigator:{},setInterval(){},addEventListener(){},Date};
vm.runInNewContext(fs.readFileSync(require.resolve('../dist/gantry-controls.js'),'utf8'),sandbox);
sandbox.GantryControls.mount(axes,jog,text=>message=text);
(async()=>{
 axes.X.last.position_full_steps=25;
 await node('setMaxHereX').onclick();
 assert.deepEqual(commands[0],{axis:'X',cmd:'set_soft_limits',fields:{enabled:true,min_full_steps:-1000000000,max_full_steps:25}});
 assert.equal(node('enableLimitsX').checked,true);assert.equal(node('maxLimitX').value,'25');
 axes.X.last.position_full_steps=-5;
 await node('setMinHereX').onclick();
 assert.deepEqual(commands.at(-2).fields,{enabled:true,min_full_steps:-5,max_full_steps:25});
 assert.equal(axes.Y.last.soft_limits_enabled,undefined);
 const count=commands.length;axes.Y.last.motor_enabled=true;
 await node('setMinHereX').onclick();assert.equal(commands.length,count);assert.match(message,/Stop both/);
 axes.Y.last.motor_enabled=false;axes.X.seen=0;
 await node('setMaxHereX').onclick();assert.equal(commands.length,count);assert.match(message,/live position/);
 axes.X.seen=Date.now();axes.X.last.position_full_steps=-5;
 await node('setMaxHereX').onclick();assert.equal(commands.length,count);assert.match(message,/different positions/);
 axes.X.last.position_full_steps=10;axes.X.send=async()=>{throw Error('USB disconnected');};
 await node('setMaxHereX').onclick();assert.match(message,/USB disconnected/);assert.equal(node('maxLimitX').value,'25');
 console.log('PASS set-current-position limits, preserve opposite bound, per-axis isolation, moving/stale/invalid gates and USB failures');
})().catch(e=>{console.error(e);process.exitCode=1;});
